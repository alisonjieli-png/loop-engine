def report(args) -> dict:
    from licensed_import.composition import library_counts, load_targets
    from licensed_import.storage import ImportStore
    from supply_lines.report import build_report
    targets = load_targets()
    library = library_counts(args.library_bundle, targets)
    library["bundle"] = Path(args.library_bundle).name
    store = ImportStore(Path(args.store_root), writes_authorized=False)
    try:
        result = build_report(store, targets, library, review_batches=Path(args.review_batches),
                              daily=Path(args.daily), slot=args.slot, ceiling=args.per_repository)
    finally:
        store.close()
    result["written_at"] = now_utc()
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(json.dumps(result, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({key: result[key] for key in ("library", "approval")}, indent=1, default=str)[:3000])
    return result


def parser() -> argparse.ArgumentParser:
    main = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = main.add_subparsers(dest="command", required=True)

    def common(sub):
        sub.add_argument("--run-folder", required=True, help="outside the repository, for example "
                         "/home/username/baltor-library/supply/<line>/<date>")
        sub.add_argument("--store-root", default="/home/username/baltor-library/import-store")
        sub.add_argument("--authorize-network-reads", action="store_true", required=True)
        sub.add_argument("--authorize-store-writes", action="store_true")
        sub.add_argument("--materialize", action="store_true", help="also write every package under the run folder")
        sub.add_argument("--maximum-requests", type=int, default=6000)
        sub.add_argument("--pause-seconds", type=float, default=0.25, help="the least pause between two requests")
        sub.add_argument("--minimum-free-gigabytes", type=float, default=MINIMUM_FREE_GIGABYTES,
                         help="store nothing when the store's disk has less free space than this")

    one = commands.add_parser("mcp-registry")
    common(one)
    one.add_argument("--maximum-entries", type=int, default=100_000)
    one.add_argument("--maximum-lookups", type=int, default=4000, help="upstream licence reads at most")
    one.add_argument("--stars", action="store_true", help="read each upstream repository's stars (GraphQL)")
    two = commands.add_parser("openapi")
    common(two)
    two.add_argument("--source", action="append", help="only these source identities of openapi_sources.json")
    two.add_argument("--stars", action="store_true", help="read each repository's stars (GraphQL)")
    directory = commands.add_parser("openapi-directory")
    common(directory)
    directory.add_argument("--api", action="append", help="only these APIs (name or provider) of the directory")
    directory.add_argument("--maximum-apis", type=int, default=0, help="at most this many APIs, in name order")
    directory.add_argument("--exclude-api", action="append", help="leave out these APIs (name or provider), so a "
                           "large directory runs in slices whose packages are stored slice by slice")
    discovery = commands.add_parser("openapi-discovery")
    common(discovery)
    discovery.add_argument("--api", action="append", help="only these API names (drive, compute, ...)")
    discovery.add_argument("--maximum-apis", type=int, default=0, help="at most this many APIs, in path order")
    three = commands.add_parser("programs")
    common(three)
    three.add_argument("--formula", action="append", help="only these formulae")
    three.add_argument("--catalogue", action="store_true",
                       help="also every formula of Homebrew's catalogue with an allowlisted licence and executables")
    three.add_argument("--maximum-programs", type=int, default=0)
    four = commands.add_parser("data-tables")
    common(four)
    four.add_argument("--table", action="append", help="only these table identities of data_table_sources.json")
    five = commands.add_parser("report")
    five.add_argument("--store-root", default="/home/username/baltor-library/import-store")
    five.add_argument("--library-bundle", required=True, help="the served release bundle folder")
    five.add_argument("--review-batches", default="/home/username/baltor-library/review-batches")
    five.add_argument("--daily", default="/home/username/baltor-library/daily")
    five.add_argument("--slot", type=int, default=2000)
    five.add_argument("--per-repository", type=int, default=15, help="the daily export's ceiling per repository")
    five.add_argument("--output", required=True, help="the report file (counts only, no third-party text)")
    return main


def main(argv=None) -> int:
    args = parser().parse_args(argv)
    # The run record states when the run began and how long it took, so each line's yield per hour is measured.
    args.started_at, args.started_clock = now_utc(), time.monotonic()
    {"mcp-registry": mcp_registry, "openapi": openapi, "openapi-directory": openapi_directory,
     "openapi-discovery": openapi_discovery, "programs": programs, "data-tables": data_tables,
     "report": report}[args.command](args)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
