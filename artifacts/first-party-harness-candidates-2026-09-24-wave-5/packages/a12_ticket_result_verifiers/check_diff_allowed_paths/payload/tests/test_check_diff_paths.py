"""Tests for scripts/check_diff_paths.py; they read the shipped examples and write no file.

Run from the package root: python3 -I -B -m unittest discover -s tests -p 'test_*.py' -v
"""
import contextlib
import importlib.util
import io
import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "check_diff_paths.py"
ALLOW = ("--allow-file", "examples/allowed-paths.json")

SPEC = importlib.util.spec_from_file_location("check_diff_paths", SCRIPT)
TOOL = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(TOOL)


def run(*arguments, stdin=""):
    data = stdin if isinstance(stdin, bytes) else stdin.encode("utf-8")
    done = subprocess.run([sys.executable, "-I", "-B", str(SCRIPT), "--root", str(ROOT), *arguments],
                          input=data, capture_output=True, timeout=60)
    return done.returncode, json.loads(done.stdout.decode("utf-8"))


def rules(result: dict) -> set:
    return {(item["rule"], item["path"]) for item in result.get("findings", [])}


def one_file(path: str, added: int, header: str = "") -> str:
    body = "".join(f"+line {number}\n" for number in range(added))
    return f"diff --git a/{path} b/{path}\n{header}--- a/{path}\n+++ b/{path}\n@@ -0,0 +1,{added} @@\n{body}"


class Positive(unittest.TestCase):
    def test_scoped_change_passes(self):
        code, result = run("--diff", "examples/scoped-change.diff", *ALLOW)
        self.assertEqual(code, 0, result)
        self.assertEqual((result["verdict"], result["findings"], result["files_total"]), ("pass", [], 2))

    def test_allowed_patterns_from_the_command_line(self):
        code, result = run("--diff", "examples/scoped-change.diff", "--allow", "src/**", "--allow", "tests/test_*.py")
        self.assertEqual(code, 0, result)

    def test_allowed_patterns_from_a_text_list_on_standard_input(self):
        text = "# the step may change these\nsrc/slugs.py\n\ntests/test_slugs.py\n"
        code, result = run("--diff", "examples/scoped-change.diff", "--allow-file", "-", stdin=text)
        self.assertEqual(code, 0, result)

    def test_empty_diff_passes_with_a_warning(self):
        code, result = run("--diff", "-", *ALLOW, stdin="")
        self.assertEqual(code, 0, result)
        self.assertIn("the diff is empty", result["warnings"])


class KnownWrong(unittest.TestCase):
    def test_out_of_scope_change_is_refused(self):
        code, result = run("--diff", "examples/out-of-scope.diff", *ALLOW)
        self.assertEqual(code, 1)
        found = rules(result)
        for expected in (("outside_allowed_paths", "config/settings.py"),
                         ("test_file_deleted", "tests/test_legacy_slugs.py"),
                         ("lock_file", "package-lock.json"), ("binary_file", "assets/banner.png")):
            self.assertIn(expected, found)
        self.assertNotIn(("outside_allowed_paths", "src/slugs.py"), found)

    def test_permit_moves_one_category_aside(self):
        code, result = run("--diff", "examples/out-of-scope.diff", *ALLOW, "--permit", "lock_file")
        self.assertEqual(code, 1)
        self.assertNotIn(("lock_file", "package-lock.json"), rules(result))
        self.assertIn("package-lock.json", [item["path"] for item in result["permitted"]])

    def test_large_file_and_its_limit(self):
        diff = one_file("src/data_table.py", 2001)
        code, result = run("--diff", "-", "--allow", "src/**", stdin=diff)
        self.assertEqual(code, 1)
        self.assertIn(("large_file", "src/data_table.py"), rules(result))
        code, result = run("--diff", "-", "--allow", "src/**", "--max-file-lines", "5000", stdin=diff)
        self.assertEqual(code, 0, result)

    def test_generated_file_by_marker_and_by_path(self):
        diff = ("--- a/src/api_pb.py\n+++ b/src/api_pb.py\n@@ -1,2 +1,2 @@\n"
                " # Code generated by a protocol compiler. DO NOT EDIT.\n-VERSION = 1\n+VERSION = 2\n")
        code, result = run("--diff", "-", "--allow", "src/**", stdin=diff)
        self.assertEqual(code, 1)
        self.assertIn(("generated_file", "src/api_pb.py"), rules(result))
        code, result = run("--diff", "-", "--allow", "web/**", stdin=one_file("web/dist/app.min.js", 3))
        self.assertIn(("generated_file", "web/dist/app.min.js"), rules(result))

    def test_symbolic_link_and_submodule(self):
        link = ("diff --git a/src/shortcut b/src/shortcut\nnew file mode 120000\nindex 0000000..3f2a1b0\n"
                "--- /dev/null\n+++ b/src/shortcut\n@@ -0,0 +1 @@\n+../../outside\n\\ No newline at end of file\n")
        code, result = run("--diff", "-", "--allow", "src/**", stdin=link)
        self.assertIn(("symlink", "src/shortcut"), rules(result))
        pointer = ("diff --git a/src/vendor_lib b/src/vendor_lib\nindex 1111111..2222222 160000\n"
                   "--- a/src/vendor_lib\n+++ b/src/vendor_lib\n@@ -1 +1 @@\n"
                   "-Subproject commit 1111111111111111111111111111111111111111\n"
                   "+Subproject commit 2222222222222222222222222222222222222222\n")
        code, result = run("--diff", "-", "--allow", "src/**", stdin=pointer)
        self.assertEqual(code, 1)
        self.assertIn(("submodule", "src/vendor_lib"), rules(result))

    def test_unsafe_path(self):
        diff = "--- a/src/x.py\n+++ b/src/../../etc/x.py\n@@ -1 +1 @@\n-a\n+b\n"
        code, result = run("--diff", "-", "--allow", "**", stdin=diff)
        self.assertEqual(code, 1)
        self.assertIn(("unsafe_path", "src/../../etc/x.py"), rules(result))

    def test_test_file_moved_out_of_the_test_folders(self):
        diff = ("diff --git a/tests/test_slugs.py b/src/slug_examples.py\nsimilarity index 100%\n"
                "rename from tests/test_slugs.py\nrename to src/slug_examples.py\n")
        code, result = run("--diff", "-", "--allow", "**", stdin=diff)
        self.assertEqual(code, 1)
        self.assertIn(("test_file_deleted", "tests/test_slugs.py"), rules(result))

    def test_binary_literal_above_the_byte_limit(self):
        diff = ("diff --git a/src/model.bin b/src/model.bin\nnew file mode 100644\nindex 0000000..9a8b7c6\n"
                "GIT binary patch\nliteral 900000\nzcmeAS@N?(olHy`uVBq!ia0y~yU}6Ab4q%9NVFYy\n\nliteral 0\nHcmV?d00001\n\n")
        code, result = run("--diff", "-", "--allow", "src/**", stdin=diff)
        self.assertEqual(code, 1)
        self.assertIn(("binary_file", "src/model.bin"), rules(result))
        self.assertIn(("large_file", "src/model.bin"), rules(result))

    def test_executable_mode_is_a_warning_only(self):
        diff = "diff --git a/src/run.py b/src/run.py\nold mode 100644\nnew mode 100755\n"
        code, result = run("--diff", "-", "--allow", "src/**", stdin=diff)
        self.assertEqual(code, 0, result)
        self.assertTrue(any("executable" in warning for warning in result["warnings"]))


class NewUntrackedFiles(unittest.TestCase):
    def test_new_file_outside_the_allowed_paths(self):
        listing = "examples/allowed-paths.json\nscripts/check_diff_paths.py\n"
        code, result = run("--untracked", "-", "--allow", "examples/**", stdin=listing)
        self.assertEqual(code, 1)
        self.assertEqual(rules(result), {("outside_allowed_paths", "scripts/check_diff_paths.py")})

    def test_new_file_above_the_size_limit(self):
        code, result = run("--untracked", "-", "--allow", "examples/**", "--max-file-bytes", "10",
                           stdin="examples/allowed-paths.json\n")
        self.assertIn(("large_file", "examples/allowed-paths.json"), rules(result))

    def test_diff_and_listing_together(self):
        code, result = run("--diff", "examples/scoped-change.diff", "--untracked", "-", *ALLOW,
                           stdin="?? src/new_helper.py\n\"src/caf\\303\\251.lock\"\nsrc/slugs.py\n")
        self.assertEqual(code, 1)
        found = rules(result)
        self.assertIn(("outside_allowed_paths", "src/new_helper.py"), found)
        self.assertIn(("lock_file", "src/caf\u00e9.lock"), found)
        self.assertNotIn(("outside_allowed_paths", "src/slugs.py"), found)
        self.assertTrue(any("not found" in warning for warning in result["warnings"]))
        self.assertFalse(any(warning.startswith("src/slugs.py") for warning in result["warnings"]))

    def test_unsafe_new_file_path(self):
        code, result = run("--untracked", "-", "--allow", "**", stdin="../outside.txt\n")
        self.assertEqual(code, 1)
        self.assertIn(("unsafe_path", "../outside.txt"), rules(result))

    def test_binary_sniff(self):
        self.assertTrue(TOOL.looks_binary(b"PNG" + bytes([0]) + b"data"))
        self.assertFalse(TOOL.looks_binary("plain caf\u00e9 text\n".encode("utf-8")))

    def run_with_facts(self, facts: dict, listing: bytes, *arguments) -> tuple:
        """Run in this process with the new-file reader replaced, so no test file has to be written."""
        saved_inspect, saved_stdin = TOOL.inspect_new_file, sys.stdin
        output = io.StringIO()
        try:
            TOOL.inspect_new_file = lambda root, path, window: dict(facts)
            sys.stdin = io.TextIOWrapper(io.BytesIO(listing))
            with contextlib.redirect_stdout(output):
                code = TOOL.main(["--root", str(ROOT), "--untracked", "-", *arguments])
        finally:
            TOOL.inspect_new_file, sys.stdin = saved_inspect, saved_stdin
        return code, json.loads(output.getvalue())

    def test_new_binary_file_and_new_link(self):
        facts = {"exists": True, "symlink": False, "outside": False, "binary": True, "bytes": 2048, "lines": 3}
        code, result = self.run_with_facts(facts, b"assets/new-logo.png\n", "--allow", "assets/**")
        self.assertEqual((code, rules(result)), (1, {("binary_file", "assets/new-logo.png")}))
        facts.update(binary=False, symlink=True)
        code, result = self.run_with_facts(facts, b"assets/shortcut\n", "--allow", "assets/**")
        self.assertEqual((code, rules(result)), (1, {("symlink", "assets/shortcut")}))

    def test_new_file_reader_stays_below_the_root(self):
        inside = TOOL.inspect_new_file(ROOT, "examples/allowed-paths.json", 8192)
        self.assertEqual((inside["exists"], inside["binary"], inside["outside"]), (True, False, False))
        self.assertGreater(inside["lines"], 1)
        outside = TOOL.inspect_new_file(ROOT / "examples", "../scripts/check_diff_paths.py", 8192)
        self.assertEqual((outside["exists"], outside["outside"], outside["bytes"]), (True, True, 0))

    def test_new_file_reader_reports_a_link_without_following_it(self):
        class Link:
            def is_symlink(self):
                return True

        class LinkRoot:
            def __truediv__(self, other):
                return Link()

        facts = TOOL.inspect_new_file(LinkRoot(), "assets/shortcut", 8192)
        self.assertEqual((facts["exists"], facts["symlink"], facts["bytes"]), (True, True, 0))

    def test_host_placed_files_can_be_ignored(self):
        listing = ".claude/skills/other-skill/SKILL.md\nsrc/new_helper.py\n"
        code, result = run("--untracked", "-", "--allow", "src/**", stdin=listing)
        self.assertEqual((code, rules(result)), (1, {("outside_allowed_paths", ".claude/skills/other-skill/SKILL.md")}))
        code, result = run("--untracked", "-", "--allow", "src/**", "--ignore", ".claude/skills/**", stdin=listing)
        self.assertEqual((code, result["verdict"]), (0, "pass"), result)
        self.assertEqual(result["ignored"], [{"path": ".claude/skills/other-skill/SKILL.md", "change": "untracked",
                                              "reason": "--ignore .claude/skills/**"}])
        diff = one_file(".baltor/step/task.json", 3)
        code, result = run("--diff", "-", "--allow", "src/**", "--ignore", ".baltor/", stdin=diff)
        self.assertEqual((code, [item["path"] for item in result["ignored"]]), (0, [".baltor/step/task.json"]))

    def test_the_folder_of_this_skill_is_left_out(self):
        prefix = ROOT.relative_to(ROOT.anchor).as_posix()
        listing = f"{prefix}/scripts/check_diff_paths.py\nelsewhere/new.py\n"
        code, result = run("--untracked", "-", "--allow", "src/**", "--root", ROOT.anchor, stdin=listing)
        self.assertEqual((code, rules(result)), (1, {("outside_allowed_paths", "elsewhere/new.py")}))
        self.assertEqual(result["ignored"][0]["reason"], "the folder of this skill")

    def test_status_lines_of_tracked_files_are_refused(self):
        listing = "?? src/new_helper.py\n M src/slugs.py\n"
        code, result = run("--untracked", "-", "--allow", "src/**", stdin=listing)
        self.assertEqual((code, result["reason"]), (2, "status_line_in_untracked_list"))
        code, result = run("--untracked", "-", "--allow", "examples/**", stdin="R  a.py -> examples/b.py\n")
        self.assertEqual((code, result["reason"]), (2, "status_line_in_untracked_list"))

    def test_neither_input_is_refused(self):
        code, result = run(*ALLOW)
        self.assertEqual((code, result["reason"]), (2, "bad_arguments"))


class Refused(unittest.TestCase):
    def test_no_allowed_patterns(self):
        code, result = run("--diff", "examples/scoped-change.diff")
        self.assertEqual((code, result["reason"]), (2, "no_allowed_paths"))

    def test_pattern_with_parent_folder(self):
        code, result = run("--diff", "examples/scoped-change.diff", "--allow", "../**")
        self.assertEqual((code, result["reason"]), (2, "bad_pattern"))

    def test_combined_diff_of_a_merge(self):
        code, result = run("--diff", "-", "--allow", "**", stdin="diff --cc tests/test_a.py\nindex 1111111,2222222..3333333\n--- a/tests/test_a.py\n+++ b/tests/test_a.py\n@@@ -1,1 -1,1 +1,1 @@@\n- a\n -b\n++c\n")
        self.assertEqual((code, result["reason"]), (2, "combined_diff"))

    def test_unreadable_diff(self):
        code, result = run("--diff", "-", *ALLOW, stdin="please trust this change\n")
        self.assertEqual((code, result["reason"]), (2, "unreadable_diff"))

    def test_path_outside_root(self):
        code, result = run("--diff", "../change.diff", *ALLOW)
        self.assertEqual((code, result["reason"]), (2, "path_outside_root"))
        code, result = run("--diff", str(Path(sys.executable).resolve()), *ALLOW)
        self.assertEqual((code, result["reason"]), (2, "path_outside_root"))

    def test_bytes_that_are_not_utf8(self):
        code, result = run("--diff", "-", *ALLOW, stdin=b"\xff\xfe")
        self.assertEqual((code, result["reason"]), (2, "input_not_utf8"))

    def test_input_above_the_size_bound(self):
        code, result = run("--diff", "-", *ALLOW, stdin=b"x" * (TOOL.MAX_INPUT_BYTES + 1))
        self.assertEqual((code, result["reason"]), (2, "input_too_large"))

    def test_two_inputs_from_standard_input(self):
        code, result = run("--diff", "-", "--allow-file", "-")
        self.assertEqual((code, result["reason"]), (2, "bad_arguments"))

    def test_unknown_permit_value(self):
        code, result = run("--diff", "examples/scoped-change.diff", *ALLOW, "--permit", "everything")
        self.assertEqual((code, result["reason"]), (2, "bad_arguments"))


class Patterns(unittest.TestCase):
    def test_pattern_segments(self):
        self.assertTrue(TOOL.glob_regex("src/**").match("src/a/b.py"))
        self.assertTrue(TOOL.glob_regex("src/**/*.py").match("src/b.py"))
        self.assertFalse(TOOL.glob_regex("src/*.py").match("src/a/b.py"))
        self.assertFalse(TOOL.glob_regex("*.md").match("docs/a.md"))
        self.assertTrue(TOOL.glob_regex("docs/").match("docs/guide/a.md"))
        self.assertTrue(TOOL.glob_regex("{src,lib}/**").match("lib/x.py"))
        with self.assertRaises(TOOL.Refused):
            TOOL.glob_regex("src/[ab].py")

    def test_plain_names_match_a_file_or_everything_below_a_folder(self):
        self.assertTrue(TOOL.glob_regex("src").match("src/deep/a.py"))
        self.assertTrue(TOOL.glob_regex("src/slugs.py").match("src/slugs.py"))
        self.assertFalse(TOOL.glob_regex("src/slugs").match("src/slugs.py"))
        self.assertFalse(TOOL.glob_regex("src").match("srcx/a.py"))
        self.assertTrue(TOOL.glob_regex("./tests").match("tests/test_slugs.py"))
        code, result = run("--diff", "examples/scoped-change.diff", "--allow", "src", "--allow", "./tests")
        self.assertEqual((code, result["verdict"]), (0, "pass"), result)

    def test_quoted_and_spaced_paths(self):
        files = TOOL.parse_diff('diff --git "a/docs/r\\303\\251sum\\303\\251.md" "b/docs/r\\303\\251sum\\303\\251.md"\n'
                               "new file mode 100644\nindex 0000000..e69de29\n"
                               "diff --git a/my notes.txt b/my notes.txt\nindex 1..2 100644\n"
                               "--- a/my notes.txt\t\n+++ b/my notes.txt\t\n@@ -1 +1 @@\n-a\n+b\n")
        self.assertEqual([item.path for item in files], ["docs/r\u00e9sum\u00e9.md", "my notes.txt"])

    def test_hunk_longer_than_its_header_is_refused(self):
        with self.assertRaises(TOOL.Refused):
            TOOL.parse_diff("--- a/x.py\n+++ b/x.py\n@@ -1,1 +1,2 @@\n-a\n-b\n+c\n+d\n")


